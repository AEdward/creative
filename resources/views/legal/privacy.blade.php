<p>This policy explains what personal information Creative Lab Academy ("we", "us") collects when you use creativelabet.com, why we collect it, and the choices you have. We handle personal data in line with Ethiopia's Personal Data Protection Proclamation No. 1321/2024 and other applicable law.</p>

<h2>1. Information we collect</h2>
<ul>
    <li><strong>Account details:</strong> your name, email address, password (stored only in scrambled, hashed form), and optionally a phone number and profile photo.</li>
    <li><strong>Learning activity:</strong> courses you enroll in, lessons completed, video progress, quiz answers and scores, assignments you submit, certificates issued, and reviews and messages you send.</li>
    <li><strong>Payments:</strong> the course, amount, payment method, transaction reference and any payment receipt or screenshot you upload. We do not store card numbers or mobile-money PINs.</li>
    <li><strong>Support:</strong> tickets, live chat messages and contact-form messages.</li>
    <li><strong>Technical data:</strong> IP address, browser and device type, and sign-in times, used for security and to keep the site working.</li>
</ul>

<h2>2. How we use it</h2>
<ul>
    <li>To create your account, give you access to the courses you enroll in and track your progress.</li>
    <li>To process payments, confirm bank transfers, handle refund requests and keep financial records.</li>
    <li>To mark quizzes and assignments and issue certificates (your name appears on certificates you earn).</li>
    <li>To send service messages: sign-in, verification and password emails, receipts, course announcements and support replies. You can turn optional notifications off in your notification settings.</li>
    <li>To protect the academy by preventing fraud, account sharing, abuse and unauthorized access.</li>
    <li>To improve courses and the site, using totals and statistics rather than individual profiles.</li>
</ul>
<p>We do not sell your personal information and we do not use it for third-party advertising.</p>

<h2>3. Who can see it</h2>
<ul>
    <li><strong>Academy staff</strong>, only as far as their role requires (for example, finance staff see payments and support staff see tickets).</li>
    <li><strong>Instructors</strong> may see the names, progress and submitted work of learners in their own courses.</li>
    <li><strong>Service providers</strong> that run parts of the site for us: our web host, Cloudflare (website delivery and private video and file storage), and our email provider. They may only use the data to provide their service to us.</li>
    <li><strong>Authorities</strong>, when the law requires it.</li>
</ul>
<p>Some of these providers store data outside Ethiopia. We use providers with strong security practices and share only what is needed.</p>

<h2>4. How long we keep it</h2>
<p>We keep your account and learning record while your account is open, so you keep lifetime access to your courses and certificates. Payment records are kept for as long as tax and accounting law requires. Unfinished uploads and temporary files are deleted automatically. When you close your account we delete or anonymise your personal data, except records we must keep by law.</p>

<h2>5. Security</h2>
<p>Passwords are hashed, the site uses encrypted HTTPS connections, videos and submitted work are kept in private storage with short-lived links, staff accounts use two-step sign-in, and access is limited by role. No system is perfectly secure, so please use a strong, unique password and do not share your account.</p>

<h2>6. Your rights</h2>
<p>You can ask to see, correct, download or delete your personal data, or object to how we use it. You can update most details yourself on your Profile page. For anything else, contact us using the details below and we will reply within 30 days. You may also complain to the relevant Ethiopian data protection authority.</p>

<h2>7. Children</h2>
<p>Learners under 18 should use the academy with the permission and supervision of a parent or guardian, who is responsible for any purchase.</p>

