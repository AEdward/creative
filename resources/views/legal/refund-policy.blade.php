<p>We want you to be happy with your course. This policy explains when and how you can ask for your money back.</p>

<h2>1. How refunds work</h2>
<p>Every refund request is reviewed individually by our team. We look at how long ago you enrolled, how much of the course you have used, and the reason you give. We will be fair and explain our decision.</p>

<h2>2. When a refund is likely</h2>
<ul>
    <li>You were charged twice, or charged the wrong amount.</li>
    <li>You paid but never received access, and we could not fix it.</li>
    <li>The course is seriously different from what its course page described, or has technical problems we could not resolve.</li>
    <li>You ask soon after enrolling and have watched or completed only a small part of the course.</li>
</ul>

<h2>3. When a refund is unlikely</h2>
<ul>
    <li>You have completed most of the course, or received a certificate for it.</li>
    <li>The course was free, or bought with a 100% coupon.</li>
    <li>The account was suspended for breaking our <a href="{{ route('terms') }}">Terms of use</a>, such as sharing access.</li>
    <li>You changed your mind a long time after enrolling.</li>
</ul>

<h2>4. How to ask</h2>
<ol>
    <li>Sign in and open <strong>Orders &amp; payments</strong> in your account.</li>
    <li>Choose the payment and select <strong>Request a refund</strong>.</li>
    <li>Tell us the reason. Clear details help us decide faster.</li>
</ol>
<p>You will get a notification and an email with the decision, normally within 7 working days.</p>

<h2>5. How you are paid back</h2>
<p>Approved refunds are paid back the same way you paid where possible (for example, to the bank or mobile-money account you used), normally within 14 working days of approval. We may ask you to confirm account details. Bank or transfer charges that we did not receive may be deducted.</p>

<h2>6. After a refund</h2>
<p>When a refund is approved, your access to that course ends and any certificate for it is withdrawn.</p>

<h2>7. Your legal rights</h2>
<p>This policy does not affect any rights you have under Ethiopian consumer protection law.</p>

